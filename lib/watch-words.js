const norm = (s) => (s || "").toLowerCase().replace(/\s+/g, "");
export function isExcluded(title, list = EXCLUDE) {
  const t = norm(title);
  return list.some((x) =>
    x instanceof RegExp ? x.test(t) : Array.isArray(x) ? x.every((w) => t.includes(norm(w))) : norm(x) && t.includes(norm(x))
  );
}

// 마감까지 이 일수 이내로 남은 공고는 준비가 어려워 알림·표시하지 않음
export const SKIP_DAYS = 5;
export const tooClose = (closeAt) =>
  !!closeAt && new Date(closeAt).getTime() - Date.now() < SKIP_DAYS * 864e5;

